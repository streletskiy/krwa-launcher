// Keep the two legacy build-tool interfaces compatible with patched glob tooling.
// Remove these adapters when dir-compare and temp update their upstream APIs.
const fs = require('node:fs')
const path = require('node:path')

function patch(file, before, after) {
    const target = require.resolve(file)
    // eslint-disable-next-line security/detect-non-literal-fs-filename -- Only the two hardcoded build dependencies below call this helper.
    const source = fs.readFileSync(target, 'utf8')
    if (source.includes(after)) return
    if (!source.includes(before)) throw new Error(`Review the dependency adapter for ${path.basename(target)}`)
    // eslint-disable-next-line security/detect-non-literal-fs-filename -- The output is the same resolved build dependency, never user input.
    fs.writeFileSync(target, source.replace(before, after))
}

patch('dir-compare/build/src/FilterHandler/defaultFilterHandler.js',
    'const minimatch_1 = __importDefault(require("minimatch"));',
    'const minimatch_1 = { default: require("minimatch").minimatch };')

// temp only cleans literal paths generated by its own mkdir/open functions.
patch('temp/lib/temp.js', "let rimraf     = require('rimraf');",
    `const cleanupOptions = options => ({ recursive: true, force: true, maxRetries: options?.maxBusyTries ?? 3 });
let rimraf = (target, options, callback) => fs.rm(target, cleanupOptions(options), callback);
rimraf.sync = (target, options) => fs.rmSync(target, cleanupOptions(options));`)
